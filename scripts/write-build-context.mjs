import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Bake Netlify's build-time CONTEXT into a server module. Anything other than
// the exact value "production" (including unset) is non-production.
const context = process.env.CONTEXT === 'production' ? 'production' : 'non-production';
const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'build-context.generated.ts');
const source = `// Generated by scripts/write-build-context.mjs. The committed value is the safe default.
// Netlify sets CONTEXT for the build only. Serverless functions do not receive it
// at runtime (runtime read-only vars are URL, SITE_NAME, and SITE_ID).
export const SSG_BUILD_CONTEXT: string = ${JSON.stringify(context)};
`;

writeFileSync(file, source);
console.log(`Build context baked as ${context}.`);

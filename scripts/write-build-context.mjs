import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const defaultFile = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'build-context.generated.ts');

/** Netlify CONTEXT is live only when it is exactly "production". */
export function bakedContextValue(context) {
  return context === 'production' ? 'production' : 'non-production';
}

/** A production build must not ship a non-production bake. */
export function productionBakeFailed(context, baked) {
  return context === 'production' && baked !== 'production';
}

export function renderBuildContext(baked) {
  return `// Generated by scripts/write-build-context.mjs. The committed value is the safe default.
// Netlify sets CONTEXT for the build only. Serverless functions do not receive it
// at runtime (runtime read-only vars are URL, SITE_NAME, and SITE_ID).
export const SSG_BUILD_CONTEXT: string = ${JSON.stringify(baked)};
`;
}

export function readBakedValue(source) {
  const match = source.match(/SSG_BUILD_CONTEXT:\s*string\s*=\s*"([^"]+)"/);
  return match ? match[1] : '';
}

/**
 * Write the bake, then read it back. Returns 1 when CONTEXT is production but
 * the persisted value is not. Does not run on import.
 */
export function main(env = process.env, file = defaultFile) {
  const context = env.CONTEXT;
  const source = renderBuildContext(bakedContextValue(context));
  writeFileSync(file, source);
  const persisted = readBakedValue(readFileSync(file, 'utf8'));
  if (productionBakeFailed(context, persisted)) {
    console.error(JSON.stringify({ event: 'lead_mode_mismatch', baked: persisted || 'missing' }));
    return 1;
  }
  console.log(`Build context baked as ${persisted}.`);
  return 0;
}

function invokedDirectly() {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return import.meta.url === pathToFileURL(realpathSync(entry)).href;
  } catch {
    return false;
  }
}

if (invokedDirectly()) {
  const code = main();
  if (code) process.exit(code);
}
